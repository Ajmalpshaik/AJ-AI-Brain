"""Repair dangling edge endpoints in a graphify extraction, before the graph is built.

WHY THIS EXISTS
---------------
graphify's health check reported 203 dangling-endpoint edges on 2026-08-13 - edges whose
source or target names a node that does not exist. The build does not warn about these at
run time; it silently drops them (1,549 extraction edges became 1,356 in graph.json). So the
loss was real, invisible, and nobody would have found it without running `diagnose_extraction`.

They are NOT one problem. Measured, they are four, and only the last is genuinely worthless:

  A  EXTERNAL MODULES (111 endpoints) - `ref_node_fs`, `ref_zod`, `sys`, `json`, `pathlib`.
     The AST extractor emits an import EDGE for every dependency but only creates NODES for
     files inside the corpus. So "brain_common.py imports sys" is a true, useful edge pointing
     at a node that was never made. Creating the node keeps the dependency information.

  B  FILE-LEVEL REFERENCES (9) - e.g. `knowledge_brain_log`, which is exactly the ID stem of a
     real file. A subagent referred to the document as a whole and no document node existed.

  C  CONCEPT REFERENCES INTO ANOTHER CHUNK (56) - e.g.
     `knowledge_live_model_views_verify_view_state`. The subagent that wrote the edge did not
     have views.md in its chunk, so it invented a plausible ID for a concept the chunk that DID
     have the file named differently. Remapped to that file's own node: weaker than the intended
     edge, but true - the thing referred to does live in that file.

  D  UNRESOLVABLE (50) - no file, no node, no unique match. Dropped, and counted out loud.

WHY A SCRIPT AND NOT A ONE-OFF EDIT
-----------------------------------
Every one of these is regenerated by the next extraction. Hand-patching the JSON once would
look fixed and silently rot. This runs as a pipeline step and prints what it did.

Idempotent: running it twice changes nothing the second time.

    python tools/graphify-repair.py                 repair graphify-out/.graphify_extract.json
    python tools/graphify-repair.py --dry-run       report only, write nothing
"""

import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXTRACT = ROOT / "graphify-out" / ".graphify_extract.json"

SKIP_DIRS = (".git", "graphify-out", "node_modules", "venv", "model-cache", "chroma-db", "pip-cache", "pip-temp", "run-temp")
KEEP_EXT = {".md", ".cs", ".py", ".js", ".mjs", ".txt", ".json", ".cmd", ".ps1"}


def norm(text):
    return re.sub(r"[^a-z0-9]+", "_", str(text).lower()).strip("_")


def corpus_stems():
    """Every real file in the Brain, keyed by the ID stem graphify would give it.

    Keyed twice on purpose: by full relative path (the documented ID format) and by bare
    filename. Subagents referred to `brain_common` when the documented ID is
    `semantic_index_brain_common`, and that reference is still unambiguous when the basename
    is unique.
    """
    by_path, by_base = {}, {}
    for p in ROOT.rglob("*"):
        if not p.is_file() or p.suffix.lower() not in KEEP_EXT:
            continue
        rel = p.relative_to(ROOT)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        rel_s = str(rel).replace("\\", "/")
        by_path[norm(rel.with_suffix(""))] = rel_s
        by_base.setdefault(norm(rel.stem), []).append(rel_s)
    # Only keep basenames that are unambiguous - two README.md files must not both claim `readme`.
    return by_path, {k: v[0] for k, v in by_base.items() if len(v) == 1}


def main(argv):
    dry = "--dry-run" in argv
    if not EXTRACT.exists():
        raise SystemExit(f"No extraction at {EXTRACT}\nRun the graphify pipeline first.")

    ex = json.loads(EXTRACT.read_text(encoding="utf-8"))
    nodes, edges = ex["nodes"], ex["edges"]
    ids = {n["id"] for n in nodes}
    by_path, by_base = corpus_stems()

    missing = Counter()
    for e in edges:
        for key in ("source", "target"):
            if e.get(key) not in ids:
                missing[e[key]] += 1

    if not missing:
        print("No dangling endpoints. Nothing to repair.")
        return 0

    new_nodes, remap, dropped = [], {}, {}

    def document_node(node_id, rel):
        return {
            "id": node_id,
            "label": Path(rel).name,
            "file_type": "code" if Path(rel).suffix.lower() in {".cs", ".py", ".js", ".mjs"} else "document",
            "source_file": rel, "source_location": None, "source_url": None,
            "captured_at": None, "author": None, "contributor": None,
        }

    # PASS 1 - A and B. Both CREATE nodes, so they must finish before anything tries to
    # match against the node set. Running C in the same loop was the first version of this
    # script and it dropped ~20 `knowledge_brain_log_*` concepts that pass 2 now resolves,
    # because the `knowledge_brain_log` document node did not exist yet when C looked.
    for mid in list(missing):
        if mid.startswith("ref_") or "_" not in mid:
            label = mid[4:] if mid.startswith("ref_") else mid
            new_nodes.append({
                "id": mid,
                "label": label.replace("_", "/") + " (external)",
                "file_type": "code",
                "source_file": None, "source_location": None, "source_url": None,
                "captured_at": None, "author": None, "contributor": None,
            })
            ids.add(mid)
            continue

        rel = by_path.get(mid) or by_base.get(mid)
        if rel:
            new_nodes.append(document_node(mid, rel))
            ids.add(mid)

    # PASS 2 - C and D, now that every node pass 1 could create exists.
    for mid, count in missing.items():
        if mid in ids:
            continue

        # C - a concept inside some file. Prefer an existing ancestor node; failing that,
        # if an ancestor stem is a REAL FILE, create its document node and point there.
        # `start_here_verify_dont_trust` needs the second half: nothing referenced
        # START-HERE.md as a whole, so no `start_here` node was ever going to exist.
        cands = [i for i in ids if mid.startswith(i + "_")]
        if cands:
            remap[mid] = max(cands, key=len)
            continue

        ancestor = None
        parts = mid.split("_")
        for cut in range(len(parts) - 1, 0, -1):          # longest prefix first
            stem = "_".join(parts[:cut])
            if stem in by_path or stem in by_base:
                ancestor = stem
                break
        if ancestor:
            if ancestor not in ids:
                new_nodes.append(document_node(ancestor, by_path.get(ancestor) or by_base[ancestor]))
                ids.add(ancestor)
            remap[mid] = ancestor
            continue

        # D - nothing to point at.
        dropped[mid] = count

    kept, lost_selfloop, lost_dangling = [], 0, 0
    for e in edges:
        s = remap.get(e.get("source"), e.get("source"))
        t = remap.get(e.get("target"), e.get("target"))
        if s not in ids or t not in ids:
            lost_dangling += 1
            continue
        if s == t:
            lost_selfloop += 1
            continue
        e["source"], e["target"] = s, t
        kept.append(e)

    print(f"dangling endpoints found : {sum(missing.values())} across {len(missing)} ids\n")
    print(f"  A external nodes created : {sum(1 for n in new_nodes if n['source_file'] is None)}")
    print(f"  B document nodes created : {sum(1 for n in new_nodes if n['source_file'] is not None)}")
    print(f"  C concept refs remapped  : {len(remap)} (widened to their file's node)")
    print(f"  D dropped, unresolvable  : {len(dropped)} ids / {sum(dropped.values())} endpoints")
    print()
    print(f"  edges {len(edges)} -> {len(kept)}   (dropped {lost_dangling} dangling, {lost_selfloop} self-loop)")
    print(f"  nodes {len(nodes)} -> {len(nodes) + len(new_nodes)}")

    if dropped:
        print("\n  dropped (top 10):")
        for k, v in sorted(dropped.items(), key=lambda kv: -kv[1])[:10]:
            print(f"    {v:3}  {k}")

    if dry:
        print("\n--dry-run: nothing written.")
        return 0

    ex["nodes"] = nodes + new_nodes
    ex["edges"] = kept
    EXTRACT.write_text(json.dumps(ex, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"\nWritten: {EXTRACT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
